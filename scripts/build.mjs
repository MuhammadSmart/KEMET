// Zero-dependency build: stitches the readable app sources into the files the
// static host serves (main.js, main.css). Run: node scripts/build.mjs
//
//   main.js  = vendor/kit-runtime.head.js   (original React/page-kit runtime, untouched)
//            + src/*.js in SOURCE_ORDER     (wrapped in their own scope)
//            + vendor/kit-runtime.tail.js   (closing bracket + licenses)
//   main.css = src/styles/*.css in STYLE_ORDER
//   index.html: the first-paint shell between its <!-- build:... --> markers
//               (scripts/shell.mjs renders it from the app's components + src/shell.js)
//
// Flags:
//   --fixtures  also writes fixtures.html/fixtures.js with demo data (long name,
//               unavailable size, scent notes/families) for testing UI states.
import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildIndexHtml } from "./shell.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_ORDER = ["runtime.js", "catalog.js", "lib.js", "art.js", "components.js", "pages.js", "app.js"];
const STYLE_ORDER = ["tokens.css", "base.css", "layout.css", "components.css", "pages.css"];
const fixtures = process.argv.includes("--fixtures");

const read = (p) => readFile(path.join(root, p), "utf8");

export async function buildJs(extra = []) {
  const head = await read("vendor/kit-runtime.head.js");
  const tail = await read("vendor/kit-runtime.tail.js");
  const parts = [];
  for (const f of SOURCE_ORDER) {
    parts.push(await read(`src/${f}`));
    if (f === "catalog.js") for (const x of extra) parts.push(await read(x));
  }
  const app = parts.join("\n").replace(/^/gm, "    ");
  return `${head}\n  // ==== KEMET app — generated from src/ by scripts/build.mjs; edit src/, not this block ====\n  (function kemetApp() {\n    "use strict";\n${app}\n  })();\n${tail}`;
}

export async function buildCss() {
  const parts = [];
  for (const f of STYLE_ORDER) parts.push(`/* ---- src/styles/${f} ---- */\n` + (await read(`src/styles/${f}`)));
  return `/* KEMET — generated by scripts/build.mjs from src/styles/. Edit those files, not this one. */\n${parts.join("\n")}`;
}

function syntaxCheck(file) {
  execFileSync(process.execPath, ["--check", file], { stdio: "inherit" });
}

export async function buildAll() {
  return { js: await buildJs(), css: await buildCss(), html: (await buildIndexHtml(root)).html };
}

async function main() {
  const out = await buildAll();
  await writeFile(path.join(root, "main.js"), out.js);
  await writeFile(path.join(root, "main.css"), out.css);
  await writeFile(path.join(root, "index.html"), out.html);
  syntaxCheck(path.join(root, "main.js"));
  console.log(`main.js    ${(out.js.length / 1024).toFixed(0)} KB`);
  console.log(`main.css   ${(out.css.length / 1024).toFixed(1)} KB`);
  console.log(`index.html ${(Buffer.byteLength(out.html) / 1024).toFixed(1)} KB (with first-paint shell)`);

  if (fixtures) {
    const fx = await buildJs(["scripts/fixtures.js"]);
    await writeFile(path.join(root, "fixtures.js"), fx);
    const html = out.html
      .replace('src="main.js"', 'src="fixtures.js"')
      .replace("<title>", "<title>[FIXTURES] ");
    await writeFile(path.join(root, "fixtures.html"), html);
    syntaxCheck(path.join(root, "fixtures.js"));
    console.log("fixtures.html + fixtures.js written (demo data — do not deploy)");
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
